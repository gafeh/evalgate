from __future__ import annotations

from evalgate.core.dataset import (
    Dataset,
    ExpectedGrading,
    GradingCase,
    Rubric,
    RubricItem,
)

RUBRIC = Rubric(
    items=(
        RubricItem(id="r1", description="Initialises the accumulator", points=1.0),
        RubricItem(id="r2", description="Traverses every element once", points=2.0),
        RubricItem(id="r3", description="Returns the accumulated value", points=1.0),
    )
)

QUESTION_ID = "2026-frq-1a"
QUESTION_PROMPT = (
    "Write a method sumAll(int[] values) that returns the sum of every element."
)

ERROR_MODES = ("off_by_one", "logic", "syntax", "correct")

AWARDS: dict[str, frozenset[str]] = {
    "off_by_one": frozenset({"r1", "r3"}),
    "logic": frozenset({"r1", "r2"}),
    "syntax": frozenset(),
    "correct": frozenset({"r1", "r2", "r3"}),
}

RESPONSES: dict[str, str] = {
    "off_by_one": (
        "public int sumAll(int[] values) {\n"
        "    int total = 0;\n"
        "    for (int i = 0; i <= values.length; i++) {\n"
        "        total += values[i];\n"
        "    }\n"
        "    return total;\n"
        "}"
    ),
    "logic": (
        "public int sumAll(int[] values) {\n"
        "    int total = 0;\n"
        "    for (int i = 0; i < values.length; i++) {\n"
        "        total += values[i];\n"
        "    }\n"
        "    return total * 2;\n"
        "}"
    ),
    "syntax": (
        "public int sumAll(int[] values) {\n"
        "    int total = 0\n"
        "    for (int i = 0; i < values.length i++) {\n"
        "        total += values[i]\n"
        "    return total;\n"
    ),
    "correct": (
        "public int sumAll(int[] values) {\n"
        "    int total = 0;\n"
        "    for (int value : values) {\n"
        "        total += value;\n"
        "    }\n"
        "    return total;\n"
        "}"
    ),
}

MUST_MENTION: dict[str, tuple[str, ...]] = {
    "off_by_one": ("loop bound",),
    "logic": ("returned value",),
    "syntax": ("syntax",),
    "correct": (),
}


def synthetic_dataset(
    size: int, version: str, *, name: str = "apcs-frq-synthetic"
) -> Dataset:
    """A deterministic dataset cycling through four known error modes.

    Each mode has a hand-authored response and a hand-authored correct award
    set, so the ground truth is real rather than generated by the thing being
    measured.
    """
    cases = []
    for index in range(size):
        mode = ERROR_MODES[index % len(ERROR_MODES)]
        cases.append(
            GradingCase(
                id=f"case-{index:04d}",
                question_id=QUESTION_ID,
                question_prompt=QUESTION_PROMPT,
                rubric=RUBRIC,
                student_response=RESPONSES[mode],
                expected=ExpectedGrading(
                    awarded_item_ids=AWARDS[mode],
                    must_mention=MUST_MENTION[mode],
                    must_not_mention=("here is the full solution",),
                ),
                tags={"error_mode": mode, "unit": "arrays"},
            )
        )
    return Dataset(name=name, version=version, cases=tuple(cases))